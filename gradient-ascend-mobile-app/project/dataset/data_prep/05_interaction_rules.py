def main():
    valid_rc = {r["risk_compound"] for r in csv.DictReader(open(RC_CSV, encoding="utf-8"))}
    known_classes = {r["drug_class"] for r in csv.DictReader(open(AI_CSV, encoding="utf-8"))}

    bad_rc = sorted({rc for (_, rc, *_ ) in R if rc not in valid_rc})
    if bad_rc:
        raise SystemExit(f"rules reference unknown risk_compound(s): {bad_rc}")

    with open(OUT, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["drug_class", "risk_compound", "severity", "mechanism",
                    "dietary_guidance", "evidence_strength", "example_drugs",
                    "drug_class_present_in_dataset", "review_status"])
        for dc, rc, sev, mech, adv, ev, ex in R:
            w.writerow([dc, rc, sev, mech, adv, ev, ex,
                        "yes" if dc in known_classes else "no", REVIEW])

    sev_ct = {}
    for _, _, sev, *_ in R:
        sev_ct[sev] = sev_ct.get(sev, 0) + 1
    not_in = sorted({dc for (dc, *_ ) in R if dc not in known_classes})
    print(f"draft interaction rules written: {len(R)}  ->  {OUT}")
    print(f"severity mix: {sev_ct}")
    print(f"every row flagged: {REVIEW}")
    if not_in:
        print(f"\n{len(not_in)} rule drug_class values not present in this medicine dataset "
              f"(kept as forward-looking reference):")
        for x in not_in:
            print(f"  - {x}")


if __name__ == "__main__":
    main()
